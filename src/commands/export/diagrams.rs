//! Mermaid blocks in an export (FR-042): finding them through the quire-rs
//! fenced-block query, naming them in diagnostics, and generating the pandoc
//! Lua filter that swaps each block for its rendered image.
//!
//! Document text never reaches the filter source. The filter reads each block's
//! source and alternative text from data files whose names this module
//! generates from the block number.

use std::fmt::Write as _;

use quire_rs::{extract_diagrams, QuireDocument};

/// The generated filter, relative to the capability root; also the
/// `--lua-filter` argument.
pub(super) const FILTER: &str = "in/diagrams.lua";

/// The language tag that selects a diagram block.
const LANGUAGE: &str = "mermaid";

/// One `mermaid` block of a committed document.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct Block {
    /// The input path, as the user named it.
    pub(super) document: String,
    /// 1-based ordinal among the `mermaid` blocks of `document`.
    pub(super) ordinal: usize,
    /// 1-based line of the opening fence in the committed file.
    pub(super) line: usize,
    /// The heading of the section that holds the block.
    pub(super) section: Option<String>,
    /// The block text between the fences, as quire-rs carries it.
    pub(super) source: String,
    /// The alternative text of the image.
    pub(super) alt: String,
}

impl Block {
    /// The identification every diagnostic of FR-042 carries.
    pub(super) fn describe(&self) -> String {
        let mut text = format!(
            "{}: mermaid diagram {} (line {}",
            self.document, self.ordinal, self.line
        );
        if let Some(section) = &self.section {
            let _ = write!(text, ", section '{section}'");
        }
        text.push(')');
        text
    }
}

/// The `mermaid` blocks of the parsed `committed` document named `document`,
/// in document order. Markdown parsing stays in quire-rs (StR-004).
pub(super) fn find(document: &str, parsed: &QuireDocument) -> Vec<Block> {
    extract_diagrams(parsed, Some(LANGUAGE))
        .into_iter()
        .map(|block| {
            let ordinal = block.index + 1;
            let alt = match &block.section {
                Some(section) => format!("Mermaid diagram {ordinal}: {section}"),
                None => format!("Mermaid diagram {ordinal}"),
            };
            Block {
                document: document.to_string(),
                ordinal,
                line: block.line,
                section: block.section,
                source: block.source,
                alt,
            }
        })
        .collect()
}

/// `in/diagrams/<number>.mmd`, the source of block `number` of the export.
pub(super) fn source_file(number: usize) -> String {
    format!("in/diagrams/{number}.mmd")
}

/// `in/diagrams/<number>.alt`, the alternative text of block `number`.
pub(super) fn alt_file(number: usize) -> String {
    format!("in/diagrams/{number}.alt")
}

/// The filter source: fixed text plus `count` and `image_directory`, both
/// generated by quire and neither taken from a document.
pub(super) fn filter_source(count: usize, image_directory: &str) -> String {
    format!("local COUNT = {count}\nlocal IMAGE_DIR = \"{image_directory}\"\n{FILTER_BODY}")
}

const FILTER_BODY: &str = r#"local seen = 0

local function read(path)
  local file = io.open(path, 'rb')
  if not file then
    return nil
  end
  local data = file:read('a')
  file:close()
  return data
end

local function lf(text)
  return (text:gsub('\r\n', '\n'))
end

local function words(text)
  local inlines = pandoc.List()
  for word in text:gmatch('%S+') do
    if #inlines > 0 then
      inlines:insert(pandoc.Space())
    end
    inlines:insert(pandoc.Str(word))
  end
  return inlines
end

function CodeBlock(block)
  if not block.classes:includes('mermaid') then
    return nil
  end
  seen = seen + 1
  local k = seen
  if k > COUNT then
    -- A block quire-rs did not find: the count check below fails the export.
    return nil
  end
  local source = read('in/diagrams/' .. k .. '.mmd')
  if source == nil then
    error('mermaid block ' .. k .. ': cannot read in/diagrams/' .. k .. '.mmd')
  end
  if lf(source) ~= lf(block.text) then
    error('mermaid block ' .. k .. ': the block differs from in/diagrams/' .. k .. '.mmd')
  end
  local image = read(IMAGE_DIR .. '/' .. k .. '.png')
  if image == nil or #image == 0 then
    error('mermaid block ' .. k .. ': no image at ' .. IMAGE_DIR .. '/' .. k .. '.png')
  end
  local name = 'img/' .. k .. '.png'
  if FORMAT == 'docx' then
    pandoc.mediabag.insert(name, 'image/png', image)
  end
  local alt = read('in/diagrams/' .. k .. '.alt') or ''
  return pandoc.Para({ pandoc.Image(words(alt), name) })
end

function Pandoc(doc)
  if seen ~= COUNT then
    error('mermaid blocks: pandoc read ' .. seen .. ' and quire found ' .. COUNT)
  end
  return nil
end
"#;

#[cfg(test)]
mod tests {
    use super::*;
    use ix_trace_rs::trace;

    #[test]
    #[trace("FR-042-AC-3")]
    fn a_block_is_described_by_document_ordinal_line_and_section() {
        let block = Block {
            document: "a.md".to_string(),
            ordinal: 2,
            line: 17,
            section: Some("Next".to_string()),
            source: String::new(),
            alt: String::new(),
        };
        assert_eq!(
            block.describe(),
            "a.md: mermaid diagram 2 (line 17, section 'Next')"
        );
        let bare = Block {
            section: None,
            ..block
        };
        assert_eq!(bare.describe(), "a.md: mermaid diagram 2 (line 17)");
    }

    #[test]
    #[trace("FR-042-AC-13")]
    fn the_filter_source_holds_only_the_count_and_the_image_directory() {
        let docx = filter_source(2, "img");
        assert!(docx.starts_with("local COUNT = 2\nlocal IMAGE_DIR = \"img\"\n"));
        assert!(filter_source(3, "typ/img").contains("local IMAGE_DIR = \"typ/img\"\n"));
        let other = filter_source(5, "img");
        assert_eq!(
            docx.replace("COUNT = 2", ""),
            other.replace("COUNT = 5", "")
        );
    }
}
